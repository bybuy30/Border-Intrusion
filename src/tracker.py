"""
src/tracker.py
==============
Frame-to-frame object tracking wrapper.

This module wraps the ByteTrack / BoT-SORT trackers that ship with
Ultralytics and provides a clean interface for the rest of the pipeline.

Important notes
---------------
- Tracking IDs are temporary session IDs generated by the tracking algorithm.
  They are NOT persistent across sessions and do NOT identify real people.
- This module does NOT implement facial recognition, biometric identification,
  or any form of personal identification.
- Tracking IDs are stored in the event log only to help operators correlate
  detections within a single monitoring session.

Usage
-----
    from src.tracker import Tracker
    from src.detector import Detector

    detector = Detector("models/best.pt")
    tracker  = Tracker(tracker_type="bytetrack")

    for frame_detections in detector.detect_video("clip.mp4"):
        tracked = tracker.update(frame_detections, frame)
        for det in tracked:
            print(det.track_id, det.class_name, det.confidence)
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import List

import numpy as np

from src.detector import Detection

logger = logging.getLogger(__name__)

# Supported tracker names understood by Ultralytics
_SUPPORTED_TRACKERS = {"bytetrack", "botsort"}


class Tracker:
    """
    Wraps an Ultralytics-compatible tracker to assign temporary tracking IDs.

    This implementation uses the YOLO model's built-in ``.track()`` method
    when running on a full video, and falls back to a simple per-frame call
    when only individual frames are available.

    For the pipeline where frames are fed one at a time (e.g. from a live
    stream or a custom loop), use ``Tracker`` in combination with the
    Ultralytics ``track`` API directly (see ``track_video`` below).

    Parameters
    ----------
    tracker_type:
        Either ``"bytetrack"`` (default) or ``"botsort"``.
    """

    def __init__(self, tracker_type: str = "bytetrack") -> None:
        tracker_type = tracker_type.lower()
        if tracker_type not in _SUPPORTED_TRACKERS:
            raise ValueError(
                f"Unsupported tracker {tracker_type!r}. "
                f"Choose one of: {sorted(_SUPPORTED_TRACKERS)}"
            )
        self.tracker_type = tracker_type
        self._next_id: int = 1          # Fallback counter for mock usage
        logger.info("Tracker initialised: %s", tracker_type)

    # ── Public API ────────────────────────────────────────────────────────────

    def track_video(
        self,
        model,                          # Ultralytics YOLO instance
        video_path: str | Path,
        conf: float = 0.35,
        iou: float = 0.45,
        imgsz: int = 640,
        device: str | None = None,
        verbose: bool = False,
    ):
        """
        Run detection + tracking on a full video using the YOLO model's
        built-in ``.track()`` method.

        Yields per-frame lists of ``Detection`` objects, each with
        ``track_id`` populated.

        Parameters
        ----------
        model:
            A loaded ``ultralytics.YOLO`` instance.
        video_path:
            Path to the video file.
        conf, iou, imgsz, device, verbose:
            Passed directly to ``model.track()``.

        Yields
        ------
        list[Detection]
            Detections for one frame, with ``track_id`` set.
        """
        video_path = Path(video_path)
        if not video_path.exists():
            raise FileNotFoundError(f"Video not found: {video_path}")

        kwargs: dict = dict(
            source=str(video_path),
            tracker=f"{self.tracker_type}.yaml",
            conf=conf,
            iou=iou,
            imgsz=imgsz,
            stream=True,
            verbose=verbose,
        )
        if device is not None:
            kwargs["device"] = device

        for result in model.track(**kwargs):
            detections = self._parse_tracked_result(result)
            yield detections

    def annotate_detections(
        self,
        detections: List[Detection],
        track_ids: List[int | None],
    ) -> List[Detection]:
        """
        Attach track IDs to an existing list of Detection objects.

        Used when tracking IDs come from an external source or mock.

        Parameters
        ----------
        detections:
            Detection objects (track_id should be None).
        track_ids:
            Track IDs in the same order as detections.

        Returns
        -------
        list[Detection]
            Same detections with ``track_id`` populated.
        """
        if len(detections) != len(track_ids):
            raise ValueError(
                f"Length mismatch: {len(detections)} detections vs "
                f"{len(track_ids)} track IDs."
            )
        for det, tid in zip(detections, track_ids):
            det.track_id = tid
        return detections

    # ── Private helpers ───────────────────────────────────────────────────────

    @staticmethod
    def _parse_tracked_result(result) -> List[Detection]:
        """Convert an Ultralytics tracked Result to a list of Detection."""
        detections: List[Detection] = []
        if result.boxes is None:
            return detections

        boxes = result.boxes
        names: dict[int, str] = result.names

        has_track_ids = boxes.id is not None

        for i in range(len(boxes)):
            xyxy = boxes.xyxy[i].cpu().numpy().tolist()
            cls_id = int(boxes.cls[i].cpu().item())
            conf = float(boxes.conf[i].cpu().item())
            cls_name = names.get(cls_id, str(cls_id))
            track_id = (
                int(boxes.id[i].cpu().item()) if has_track_ids else None
            )
            detections.append(
                Detection(
                    bbox_xyxy=(xyxy[0], xyxy[1], xyxy[2], xyxy[3]),
                    class_id=cls_id,
                    class_name=cls_name,
                    confidence=conf,
                    track_id=track_id,
                )
            )
        return detections
